#include <iostream>
using namespace std;
int main() {
    int a=8,b=3;
    //addition
    cout<<"a+b= "<<(a+b)<<endl;
    //subtraction
    cout<<"a-b= "<<(a-b)<<endl;
    //multiplication
    cout<<"a*b= "<<(a*b)<<endl;
    //division
    cout<<"a/b= "<<(a/b)<<endl;
    //modulo
    cout<<"a%b= "<<(a%b)<<endl;
    //increment
    cout<<"++a= "<<(++a)<<endl;
    //decrement
    cout<<"b--= "<<(b--)<<endl;
}
